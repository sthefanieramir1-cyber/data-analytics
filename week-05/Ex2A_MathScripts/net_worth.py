# Net Worth Calculator Notes

    # Net Worth = what's "truly yours" after paying off all debts
    # Assets = everything you own (cash, property, investments, etc.)
    #  # Liabilities = all the money you owe (loans, credit cards, etc.)
        # Short-term Liabilities: Debts that are due within one year,
        #  such as credit card balances and short-term loans.

             # Calculate Net Worth: (Assets − Liabilities = Net Worth)

    # Assets Types : 

    # Liquid Assets: Cash, savings accounts, and checking accounts.
    # Tangible Assets: Physical items like houses, cars, jewelry, and furniture.
    # Intangible Assets: Non-physical assets such as stocks, bonds, and retirement accounts (e.g., 401(k), IRA)


# List of assets and liabilities
car_value = 15000
house_value = 250000
savings_account = 5000
credit_card_debt = 2000
student_loan = 15000

# Calculate total assets
total_assets = car_value + house_value + savings_account

# Calculate total debts
total_debts = credit_card_debt + student_loan

# Calculate net worth
net_worth = total_assets - total_debts

# Print the results
print(f"Total Assets are: ${total_assets}")
print(f"Total Debts are: ${total_debts}")
print(f"Net Worth is: ${net_worth}")